#!/usr/bin/env node
/*
 * Builds install/Code.gs: the whole app in ONE file (backend + page), so installing it
 * means pasting a single file into the Apps Script editor's Code.gs.
 *   node dev/build-installer.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = name => fs.readFileSync(path.join(root, 'apps-script', name), 'utf8');

function pageHtml() {
  const html = src('Index.html')
    .replace(/<\?!=\s*include\('Styles'\);?\s*\?>/, () => src('Styles.html'))
    .replace(/<\?!=\s*include\('Client'\);?\s*\?>/, () => src('Client.html'));
  if (/<\?/.test(html)) throw new Error('Unresolved template tag in page HTML');
  return html;
}

function build() {
  const lines = pageHtml().split('\n').map(l => '  ' + JSON.stringify(l));
  return [
    '/**',
    ' * Surgery Follow-ups — single-file installer.',
    ' * Paste this whole file into Code.gs in the Apps Script editor (replace everything).',
    ' * Generated by dev/build-installer.js from the apps-script/ folder — edit those, not this.',
    ' */',
    '',
    src('Code.gs').trimEnd(),
    '',
    '// ---------------------------------------------------------------------------',
    '// The app page (HTML, styles and browser code), embedded so only one file is needed.',
    '// ---------------------------------------------------------------------------',
    '',
    'var APP_HTML = [',
    lines.join(',\n'),
    "].join('\\n');",
    '',
  ].join('\n');
}

module.exports = { build: build, pageHtml: pageHtml };

if (require.main === module) {
  const out = path.join(root, 'install', 'Code.gs');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, build());
  console.log('Wrote ' + path.relative(process.cwd(), out));
}
